//! Generates static Rust weight and test-vector tables (`generated_model.rs`)
//! directly consumed by the `no_std` ESP32-WROOM-32 benchmark firmware.

use std::fmt::Write as _;
use std::path::Path;

use neural_filter_core::{
    FRAME_LEN, TEMPLATE_LEN,
    conv1d_int8::ScratchpadInt8,
    quant::{FixedPointScale, quantize_frame_i8},
};

use crate::{quantize::OwnedModelInt8, signal::FrameSample, train::OwnedModelF32};

/// Exports both FP32 and Static INT8 weights of the selected Pareto-optimal model,
/// the LFM chirp template, and verified reference test frames for on-chip parity checks.
pub fn export_esp32_model_module(
    out_path: &Path,
    model_name: &str,
    template: &[f32; TEMPLATE_LEN],
    model_f32: &OwnedModelF32,
    model_int8: &OwnedModelInt8,
    test_frames: &[(&str, &FrameSample)],
) -> std::io::Result<()> {
    let mut s = String::with_capacity(64 * 1024);

    writeln!(
        s,
        "//! AUTO-GENERATED by `research-cli` — DO NOT EDIT MANUALLY."
    )
    .unwrap();
    writeln!(
        s,
        "//! Pareto-optimal 3-layer dilated Conv1D Neural Matched Filter ({model_name}) for ESP32-WROOM-32."
    )
    .unwrap();
    writeln!(s).unwrap();
    writeln!(s, "use neural_filter_core::{{").unwrap();
    writeln!(s, "    DILATIONS,").unwrap();
    writeln!(s, "    conv1d_int8::{{Conv1dLayerInt8, NeuralFilterInt8}},").unwrap();
    writeln!(s, "    quant::FixedPointScale,").unwrap();
    writeln!(s, "}};").unwrap();
    writeln!(s, "#[cfg(feature = \"bench-fp32\")]").unwrap();
    writeln!(s, "use neural_filter_core::conv1d_f32::{{Conv1dLayerF32, NeuralFilterF32}};").unwrap();
    writeln!(s).unwrap();
    writeln!(s, "pub const MODEL_NAME: &str = \"{model_name}\";").unwrap();
    writeln!(
        s,
        "pub const HIDDEN_CHANNELS: usize = {};",
        model_int8.hidden_channels
    )
    .unwrap();
    writeln!(
        s,
        "pub const INPUT_SCALE: f32 = {:.9e}_f32;",
        model_int8.input_scale
    )
    .unwrap();
    writeln!(
        s,
        "pub const OUTPUT_SCALE: f32 = {:.9e}_f32;",
        model_int8.output_scale
    )
    .unwrap();
    writeln!(s).unwrap();

    // Chirp template (f32 and i8)
    write_f32_array(&mut s, "TEMPLATE_F32", template);
    let max_t = template.iter().fold(1e-6_f32, |m, &x| m.max(x.abs()));
    let mut template_i8 = [0_i8; TEMPLATE_LEN];
    quantize_frame_i8(template, max_t / 127.0, &mut template_i8);
    write_i8_array(&mut s, "TEMPLATE_I8", &template_i8);

    // Static INT8 weights, biases, and Q31 scales
    write_i8_array(&mut s, "L1_W_I8", &model_int8.layer1.weights);
    write_i32_array(&mut s, "L1_B_I32", &model_int8.layer1.biases);
    write_scale_array(&mut s, "L1_SCALES", &model_int8.layer1.scales);

    write_i8_array(&mut s, "L2_W_I8", &model_int8.layer2.weights);
    write_i32_array(&mut s, "L2_B_I32", &model_int8.layer2.biases);
    write_scale_array(&mut s, "L2_SCALES", &model_int8.layer2.scales);

    write_i8_array(&mut s, "L3_W_I8", &model_int8.layer3.weights);
    write_i32_array(&mut s, "L3_B_I32", &model_int8.layer3.biases);
    write_scale_array(&mut s, "L3_SCALES", &model_int8.layer3.scales);

    // FP32 weights and biases (for direct FP32 vs INT8 on-chip benchmark comparison)
    write_cfg_f32_array(&mut s, "L1_W_F32", &model_f32.layer1.weights);
    write_cfg_f32_array(&mut s, "L1_B_F32", &model_f32.layer1.biases);
    write_cfg_f32_array(&mut s, "L2_W_F32", &model_f32.layer2.weights);
    write_cfg_f32_array(&mut s, "L2_B_F32", &model_f32.layer2.biases);
    write_cfg_f32_array(&mut s, "L3_W_F32", &model_f32.layer3.weights);
    write_cfg_f32_array(&mut s, "L3_B_F32", &model_f32.layer3.biases);

    // Const model constructors
    writeln!(
        s,
        "pub const MODEL_INT8: NeuralFilterInt8<'static> = NeuralFilterInt8 {{"
    )
    .unwrap();
    writeln!(s, "    hidden_channels: HIDDEN_CHANNELS,").unwrap();
    writeln!(s, "    input_scale: INPUT_SCALE,").unwrap();
    writeln!(s, "    output_scale: OUTPUT_SCALE,").unwrap();
    writeln!(s, "    layer1: Conv1dLayerInt8 {{ c_in: 1, c_out: HIDDEN_CHANNELS, dilation: DILATIONS[0], weights: &L1_W_I8, biases: &L1_B_I32, scales: &L1_SCALES }},").unwrap();
    writeln!(s, "    layer2: Conv1dLayerInt8 {{ c_in: HIDDEN_CHANNELS, c_out: HIDDEN_CHANNELS, dilation: DILATIONS[1], weights: &L2_W_I8, biases: &L2_B_I32, scales: &L2_SCALES }},").unwrap();
    writeln!(s, "    layer3: Conv1dLayerInt8 {{ c_in: HIDDEN_CHANNELS, c_out: 1, dilation: DILATIONS[2], weights: &L3_W_I8, biases: &L3_B_I32, scales: &L3_SCALES }},").unwrap();
    writeln!(s, "}};").unwrap();
    writeln!(s).unwrap();

    writeln!(s, "#[cfg(feature = \"bench-fp32\")]").unwrap();
    writeln!(
        s,
        "pub const MODEL_F32: NeuralFilterF32<'static> = NeuralFilterF32 {{"
    )
    .unwrap();
    writeln!(s, "    hidden_channels: HIDDEN_CHANNELS,").unwrap();
    writeln!(s, "    layer1: Conv1dLayerF32 {{ c_in: 1, c_out: HIDDEN_CHANNELS, dilation: DILATIONS[0], weights: &L1_W_F32, biases: &L1_B_F32 }},").unwrap();
    writeln!(s, "    layer2: Conv1dLayerF32 {{ c_in: HIDDEN_CHANNELS, c_out: HIDDEN_CHANNELS, dilation: DILATIONS[1], weights: &L2_W_F32, biases: &L2_B_F32 }},").unwrap();
    writeln!(s, "    layer3: Conv1dLayerF32 {{ c_in: HIDDEN_CHANNELS, c_out: 1, dilation: DILATIONS[2], weights: &L3_W_F32, biases: &L3_B_F32 }},").unwrap();
    writeln!(s, "}};").unwrap();
    writeln!(s).unwrap();

    // Embedded verification frame (IndustrialHarsh) + host bit-exact INT8 checksum
    let (label, sample) = test_frames
        .last()
        .copied()
        .expect("at least one test frame");
    let mut input_q = [0_i8; FRAME_LEN];
    let mut ref_out_q = [0_i8; FRAME_LEN];
    let mut scratch = ScratchpadInt8::new();
    quantize_frame_i8(&sample.input, model_int8.input_scale, &mut input_q);
    model_int8
        .as_view()
        .infer_quantized(&input_q, &mut ref_out_q, &mut scratch);
    let checksum = fnv1a_i8(&ref_out_q);

    writeln!(s, "pub const TEST_FRAME_LABEL: &str = \"{label}\";").unwrap();
    writeln!(
        s,
        "pub const TEST_FRAME_TRUE_LAG: usize = {};",
        sample.true_lag.unwrap_or(0)
    )
    .unwrap();
    writeln!(
        s,
        "pub const REF_INT8_OUT_CHECKSUM: u32 = 0x{checksum:08X}_u32;"
    )
    .unwrap();
    write_f32_array(&mut s, "TEST_FRAME_F32", &sample.input);
    write_i8_array(&mut s, "TEST_FRAME_I8", &input_q);

    if let Some(parent) = out_path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(out_path, s)
}

fn fnv1a_i8(data: &[i8]) -> u32 {
    let mut h = 0x811C_9DC5_u32;
    for &b in data {
        h ^= (b as u8) as u32;
        h = h.wrapping_mul(0x0100_0193);
    }
    h
}

fn write_cfg_f32_array(out: &mut String, name: &str, data: &[f32]) {
    writeln!(out, "#[cfg(feature = \"bench-fp32\")]").unwrap();
    write_f32_array(out, name, data);
}

fn write_f32_array(out: &mut String, name: &str, data: &[f32]) {
    writeln!(out, "pub const {name}: [f32; {}] = [", data.len()).unwrap();
    for chunk in data.chunks(8) {
        out.push_str("    ");
        for &v in chunk {
            write!(out, "{v:.7e}_f32, ").unwrap();
        }
        out.push('\n');
    }
    writeln!(out, "];\n").unwrap();
}

fn write_i8_array(out: &mut String, name: &str, data: &[i8]) {
    writeln!(out, "pub const {name}: [i8; {}] = [", data.len()).unwrap();
    for chunk in data.chunks(16) {
        out.push_str("    ");
        for &v in chunk {
            write!(out, "{v}, ").unwrap();
        }
        out.push('\n');
    }
    writeln!(out, "];\n").unwrap();
}

fn write_i32_array(out: &mut String, name: &str, data: &[i32]) {
    writeln!(out, "pub const {name}: [i32; {}] = [", data.len()).unwrap();
    for chunk in data.chunks(8) {
        out.push_str("    ");
        for &v in chunk {
            write!(out, "{v}, ").unwrap();
        }
        out.push('\n');
    }
    writeln!(out, "];\n").unwrap();
}

fn write_scale_array(out: &mut String, name: &str, data: &[FixedPointScale]) {
    writeln!(
        out,
        "pub const {name}: [FixedPointScale; {}] = [",
        data.len()
    )
    .unwrap();
    for sc in data {
        writeln!(
            out,
            "    FixedPointScale {{ mult: {}, shift: {} }},",
            sc.mult, sc.shift
        )
        .unwrap();
    }
    writeln!(out, "];\n").unwrap();
}
